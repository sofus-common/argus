    await dialog.getByRole('button', { name: 'Value remaining holdings' }).click();
    await dialog.getByRole('region', { name: 'Dated combined P/L' }).waitFor();
    await dialog.getByRole('button', { name: 'Analyze remaining holdings', exact: true }).click();
    await page.getByRole('heading', { name: 'Remaining holdings', exact: true }).waitFor();
    assert.equal(await page.getByLabel('Contracts', { exact: true }).inputValue(), '2');
    assert.equal(await page.getByLabel('Total cost allowance', { exact: true }).inputValue(), '0');
    assert.match(await page.locator('.saved-workspace summary').innerText(), /Unsaved position/);
    assert.deepEqual(saveMutations, []);
    await page.getByRole('button', { name: 'Undo', exact: true }).click();
    assert.equal(await page.locator('.leg-list').textContent(), markedBuilder);
    assert.deepEqual(saveMutations, []);
    assert.deepEqual(errors, []);
    console.log('Lifecycle browser PASS: closes, stable-ID retry, dated valuation, malformed import rejection, explicit detached remaining analysis and Undo.');
