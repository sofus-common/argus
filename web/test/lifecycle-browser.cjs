  const projection = { status: 'options-active', active: state, stock: null, asOf: state.valuationTimestamp, requiresRevaluation: false, grossRealizedPnl: 0, allowance: 5, netClosedPnl: null };
  const closed = { ...projection, status: 'closed', active: null, grossRealizedPnl: 70, netClosedPnl: 65 };
