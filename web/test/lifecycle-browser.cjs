        assert.deepEqual(Object.keys(body).sort(), ['revision', 'void']);
        assert.deepEqual(Object.keys(body.void).sort(), ['closeId', 'id', 'reason', 'recordedAt']);
        assert.equal(body.void.closeId, commits[0].close.id);
        assert.equal(body.void.reason, 'Close recorded in error');
