    const page = await browser.newPage();
    const errors = [], commits = [];
    let valuations = 0;
    let malformedRemaining = false;
    let marketPhase = false;
    const saveMutations = [];
    let closedRecord = null;
    const corrections = [];
    const voids = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/feed/**', route => route.fulfill({ status: 503, json: { error: { message: 'Mock browser: feed disabled' } } }));
