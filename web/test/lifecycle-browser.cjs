    const builder = await page.locator('.leg-list').textContent();
    await page.getByRole('button', { name: 'Manage closes', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Manage recorded closes' });
    await dialog.getByLabel('Position action', { exact: true }).waitFor({ timeout: 5000 });
    assert.equal(await dialog.locator('form').count(), 1);
    const inventoryBox = await dialog.getByRole('heading', { name: 'Remaining inventory', exact: true }).boundingBox();
    const actionBox = await dialog.getByLabel('Position action', { exact: true }).boundingBox();
    assert.ok(inventoryBox.y < actionBox.y, 'Inventory must precede recording actions');
    await dialog.screenshot({ path: 'web/.wrangler/lifecycle-overview.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth), true);
    await dialog.screenshot({ path: 'web/.wrangler/lifecycle-overview-mobile.png' });
    await page.setViewportSize({ width: 1280, height: 720 });
    assert.equal(await dialog.getByRole('button', { name: 'Value remaining holdings' }).isDisabled(), true);
    await dialog.getByLabel('Close asset', { exact: true }).selectOption(`option:${state.legs[0].id}`);
    await dialog.getByLabel('Close quantity').fill('1');
    await dialog.getByLabel('Close price').fill('3.12345');
    await dialog.getByLabel('Close UTC datetime').fill('2026-09-04T20:00');
    await dialog.getByRole('button', { name: 'Preview close', exact: true }).click();
    await dialog.getByRole('region', { name: 'Close preview' }).waitFor();
    assert.equal(await dialog.getByLabel('Position action', { exact: true }).isDisabled(), true);
    await dialog.getByText('$3.12345 / share', { exact: false }).waitFor();
    await page.screenshot({ path: 'web/.wrangler/lifecycle-preview.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: 'web/.wrangler/lifecycle-preview-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1280, height: 720 });
    assert.equal(commits.length, 0);
    await dialog.getByRole('button', { name: 'Confirm recorded close' }).click();
    await dialog.getByRole('alert').waitFor();
    assert.equal(await dialog.getByLabel('Close quantity').isDisabled(), true);
    await dialog.getByRole('button', { name: 'Reload saved record' }).click();
    await dialog.getByText('The close is not confirmed in this reload.', { exact: false }).waitFor();
    assert.equal(await dialog.getByLabel('Close quantity').isDisabled(), true);
    await page.keyboard.press('Escape');
    assert.equal(await dialog.isVisible(), true);
    await dialog.getByRole('button', { name: 'Retry identical close' }).click();
    await dialog.getByRole('alert').filter({ hasText: 'Rate limited' }).waitFor();
    assert.equal(await dialog.getByLabel('Close quantity').isDisabled(), true);
    await dialog.getByRole('button', { name: 'Retry identical close' }).click();
    await dialog.getByText('No remaining assets. Position fully closed.').waitFor();
    assert.deepEqual(commits[0], commits[1]);
    assert.deepEqual(commits[0], commits[2]);
    await dialog.getByLabel('Position action', { exact: true }).selectOption('correction');
    assert.equal(await dialog.locator('form').count(), 1);
    await dialog.getByLabel('Correction original close').selectOption(commits[0].close.id);
    await dialog.getByLabel('Corrected close price').fill('3.98765');
    await dialog.getByLabel('Price correction reason').fill('Transcription correction');
    await dialog.getByRole('button', { name: 'Preview price correction' }).click();
    await dialog.getByRole('region', { name: 'Price correction preview' }).waitFor();
    assert.equal(corrections.length, 0);
    await dialog.getByRole('button', { name: 'Confirm price correction' }).click();
    await dialog.getByRole('alert').waitFor();
    assert.equal(await dialog.getByLabel('Corrected close price').isDisabled(), true);
    await dialog.getByRole('button', { name: 'Reload saved record' }).click();
    await dialog.getByText('The price correction is not confirmed in this reload.', { exact: false }).waitFor();
    await dialog.getByRole('button', { name: 'Retry identical price correction' }).click();
    await dialog.getByRole('alert').filter({ hasText: 'Correction rate limited' }).waitFor();
    assert.equal(await dialog.getByLabel('Corrected close price').isDisabled(), true);
    await dialog.getByRole('button', { name: 'Retry identical price correction' }).click();
    await dialog.getByText('Price correction recorded. The strategy builder has not changed.').waitFor();
    assert.deepEqual(corrections[0], corrections[1]);
    assert.deepEqual(corrections[0], corrections[2]);
    await dialog.getByText('Recorded closes · 1', { exact: true }).click();
    await dialog.getByText('Latest corrected price: $3.98765 / share', { exact: true }).waitFor();
    await dialog.getByText('original $3.12345 / share', { exact: false }).waitFor();
    await dialog.getByText('$163.77', { exact: true }).waitFor();
    await dialog.getByLabel('Position action', { exact: true }).selectOption('void');
    assert.equal(await dialog.locator('form').count(), 1);
    await dialog.getByLabel('Void original close').selectOption(commits[0].close.id);
    await dialog.getByLabel('Close void reason').fill('Close recorded in error');
    await dialog.getByRole('button', { name: 'Preview close void' }).click();
    const voidPreview = dialog.getByRole('region', { name: 'Close void preview' });
    await voidPreview.waitFor();
    await voidPreview.getByText(`1 contracts · long ${state.legs[0].contractId}`, { exact: true }).waitFor();
    await voidPreview.getByText('$0.00', { exact: true }).waitFor();
    assert.equal(voids.length, 0);
    await dialog.getByRole('button', { name: 'Void erroneous close', exact: true }).click();
    await dialog.getByRole('alert').waitFor();
    await dialog.getByRole('button', { name: 'Reload saved record' }).click();
    await dialog.getByText('The close void is not confirmed in this reload.', { exact: false }).waitFor();
    assert.equal(await dialog.getByLabel('Close void reason').isDisabled(), true);
    await dialog.getByRole('button', { name: 'Retry identical close void' }).click();
    await dialog.getByRole('alert').filter({ hasText: 'Void rate limited' }).waitFor();
    assert.equal(await dialog.getByLabel('Close void reason').isDisabled(), true);
    await dialog.getByRole('button', { name: 'Retry identical close void' }).click();
