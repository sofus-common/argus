const { chromium } = require('playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1536, height: 1024 } });
    const errors = [];
    const dependencies = new Map();
    page.on('request', request => { const url = new URL(request.url()); dependencies.set(url.pathname.split('/').pop(), request.url()); });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:5174/prototype.html');
    await page.getByLabel('Thesis horizon', { exact: true }).fill('2026-09-10');
    const before = await page.locator('.lab-position').innerText();
    await page.getByRole('button', { name: 'Optimize · sample', exact: true }).click();
    assert.equal(await page.locator('.lab-position').count(), 0, 'Optimizer must replace, not expand, the workbench');
    assert.equal(await page.locator('table').count(), 0, 'Results must use cards, not the old table');
    await page.locator('.opt-card').first().waitFor();
    assert.equal(await page.getByRole('button', { name: 'Neutral', exact: true }).isDisabled(), true);
    await page.getByLabel('Optimizer maximum loss').fill('15000');
    await page.getByLabel('Optimizer collateral limit').fill('15000');
    await page.getByRole('button', { name: 'Search strategies', exact: true }).click();
    assert.equal(await page.locator('.opt-card').count(), 6);
    await page.getByRole('button', { name: 'Expiry Sep 11, 2026', exact: true }).click();
    assert.equal(await page.locator('.opt-card').count(), 0, 'Expiry changes invalidate results');
    assert.equal(await page.getByLabel('Optimizer thesis horizon').inputValue(), '2026-09-10');
    await page.getByRole('button', { name: 'Expiry Sep 18, 2026', exact: true }).click();
    await page.getByRole('button', { name: 'Search strategies', exact: true }).click();
    await page.getByRole('button', { name: 'Preview candidate 1', exact: true }).click();
    await page.getByRole('dialog', { name: 'Review candidate before applying' }).waitFor();
    await page.keyboard.press('Escape');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.setViewportSize({ width: 1536, height: 1024 });
    await page.screenshot({ path: '.wrangler/lab-optimizer-screen.png', fullPage: true });
    await page.getByRole('button', { name: 'Workbench', exact: true }).click();
    assert.equal(await page.locator('.lab-position').innerText(), before, 'Back must preserve the draft');
    await page.getByRole('button', { name: 'Optimize · sample', exact: true }).click();
    await page.getByRole('button', { name: 'Preview candidate 1', exact: true }).click();
    const family = await page.locator('.opt-confirm h2').innerText();
    await page.getByRole('button', { name: 'Apply to draft', exact: true }).click();
    assert.ok((await page.locator('.lab-position h1').innerText()).includes(family));
    await page.getByRole('button', { name: 'Optimize · sample', exact: true }).click();
    await page.getByRole('button', { name: 'Expiry Mar 19, 2027', exact: true }).click();
    await page.getByLabel('Optimizer thesis horizon').fill('2027-03-12');
    await page.getByLabel('Optimizer maximum loss').fill('15000');
    await page.getByRole('button', { name: 'Search strategies', exact: true }).click();
    await page.getByRole('button', { name: 'Preview candidate 1', exact: true }).click();
    await page.getByRole('button', { name: 'Apply to draft', exact: true }).click();
    assert.equal(await page.getByLabel('Workbench expiry').inputValue(), '2027-03-19T20:00:00.000Z');
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    await page.reload();
    await page.getByRole('button', { name: 'Open draft', exact: true }).click();
    assert.equal(await page.getByLabel('Workbench expiry').inputValue(), '2027-03-19T20:00:00.000Z');
    const fixture = await browser.newPage({ viewport: { width: 900, height: 400 } });
    fixture.on('pageerror', error => errors.push(error.message));
    await fixture.route('**/expiry-strip-fixture', route => route.fulfill({ contentType: 'text/html', body: `<div id="root"></div><script type="module">
      import RefreshRuntime from '/@react-refresh';
      RefreshRuntime.injectIntoGlobalHook(window);
      window.$RefreshReg$ = () => {}; window.$RefreshSig$ = () => type => type;
      window.__vite_plugin_react_preamble_installed__ = true;
    </script><script type="module">
      import React from '${dependencies.get('react.js')}';
      import ReactDOM from '${dependencies.get('react-dom_client.js')}';
      import {ExpiryStrip} from '/src/scenario-lab-optimizer.tsx';
      const dates = ['2026-09','2026-10','2026-11','2026-12','2027-01','2027-02','2027-03'].flatMap(month=>[11,18,25].map(day=>month+'-'+day+'T20:00:00.000Z'));
      function Demo(){const [date,setDate]=React.useState(dates[0]);return React.createElement('main',{className:'opt-screen'},React.createElement(ExpiryStrip,{expiry:date,onChange:setDate,dates}));}
      ReactDOM.createRoot(document.getElementById('root')).render(React.createElement(Demo));
    </script>` }));
    await fixture.goto('http://127.0.0.1:5174/expiry-strip-fixture');
    const strip = fixture.locator('.opt-strip-track');
    await strip.waitFor().catch(error => { throw new Error(errors.join('\n') || error.message); });
    await fixture.getByRole('button', { name: 'Later months', exact: true }).click();
    await fixture.waitForFunction(() => document.querySelector('.opt-strip-track').scrollLeft > 0);
    assert.equal(await fixture.locator('[aria-pressed=true]').getAttribute('aria-label'), 'Expiry Sep 11, 2026', 'Arrow pans, never selects');
    await fixture.getByRole('button', { name: 'Earlier months', exact: true }).click();
    await fixture.waitForFunction(() => document.querySelector('.opt-strip-track').scrollLeft === 0);
    const bounds = await strip.boundingBox();
    await fixture.mouse.move(bounds.x + 140, bounds.y + 35);
    await fixture.mouse.down();
    await fixture.mouse.move(bounds.x + 20, bounds.y + 35, { steps: 10 });
    await fixture.mouse.up();
    assert.ok(await strip.evaluate(node => node.scrollLeft > 50), 'Dragging pans months');
    assert.equal(await fixture.locator('[aria-pressed=true]').getAttribute('aria-label'), 'Expiry Sep 11, 2026', 'Drag release does not select');
    await fixture.getByRole('button', { name: 'Expiry Nov 18, 2026', exact: true }).click();
    assert.equal(await fixture.locator('[aria-pressed=true]').getAttribute('aria-label'), 'Expiry Nov 18, 2026');
    await fixture.getByRole('button', { name: 'Expiry Nov 25, 2026', exact: true }).press('Enter');
    assert.equal(await fixture.locator('[aria-pressed=true]').getAttribute('aria-label'), 'Expiry Nov 25, 2026');
    await fixture.locator('.opt-expiry-strip').screenshot({ path: '.wrangler/expiry-strip-multimonth-fixture.png' });
    await fixture.close();
    assert.deepEqual(errors, []);
    console.log('PASS dedicated screen, six cards, expiry isolation, invalidation, preview/Escape, mobile, Back and Apply');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
