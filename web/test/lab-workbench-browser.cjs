const { chromium } = require('playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.env.PROTOTYPE_URL || 'http://127.0.0.1:5174/prototype.html');
    await page.getByLabel('Thesis horizon', { exact: true }).fill('2026-09-10');
    const thesis = await page.locator('#thesis').inputValue();
    const target = await page.getByLabel('Target price', { exact: true }).inputValue();
    const marker = page.getByRole('slider', { name: 'Chart selected price', exact: true });
    await marker.focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await marker.getAttribute('aria-valuenow'), '103.25');
    assert.equal(await page.getByLabel('Target price', { exact: true }).inputValue(), target, 'Chart inspection must preserve thesis target');
    const handle = await page.locator('.lac-marker rect').boundingBox();
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
    await page.mouse.down();
    await page.mouse.move(handle.x + handle.width / 2 + 65, handle.y + handle.height / 2, { steps: 8 });
    await page.mouse.up();
    assert.ok(Number(await marker.getAttribute('aria-valuenow')) > 103.25, 'Pointer drag selects price');
    await page.getByRole('button', { name: 'Heatmap', exact: true }).click();
    assert.equal(await page.locator('.lac-heatmap tbody button').count(), 63);
    await page.locator('.lac-heatmap tbody button').nth(20).click();
    assert.ok((await page.locator('.lab-selected-summary').innerText()).includes('Custom inspection'));
    await page.getByRole('button', { name: 'Table', exact: true }).click();
    assert.equal(await page.locator('.lac-table tbody tr').count(), 9);
    await page.locator('.lac-table tbody button').nth(3).click();
    assert.equal(await page.getByLabel('Target price', { exact: true }).inputValue(), target);
    assert.equal(await page.getByLabel('Thesis horizon', { exact: true }).inputValue(), '2026-09-10');
    await page.getByRole('button', { name: 'Curve', exact: true }).click();
    await page.getByRole('button', { name: 'Show thesis scenario', exact: true }).click();
    await page.screenshot({ path: '.wrangler/consolidated-workbench.png', fullPage: true });
    await page.getByRole('button', { name: 'Change strategy', exact: true }).click();
    const library = page.getByRole('dialog', { name: 'Choose your structure' });
    assert.equal(await library.locator('.lsp-template').count(), 27);
    assert.equal(await library.locator('.lsp-template:enabled').count(), 6);
    await page.screenshot({ path: '.wrangler/consolidated-library.png', fullPage: true });
    await library.getByRole('searchbox').fill('cash-secured');
    assert.equal(await library.locator('.lsp-template').count(), 1);
    await library.locator('.lsp-template').click();
    assert.ok((await page.locator('.lab-position h1').innerText()).includes('Bull call spread'), 'Browsing must not replace the position');
    await library.getByRole('button', { name: 'Use strategy', exact: true }).click();
    assert.ok((await page.locator('.lab-position h1').innerText()).includes('Cash-secured put'));
    assert.equal(await page.locator('#thesis').inputValue(), thesis);
    assert.equal(await page.getByLabel('Thesis horizon', { exact: true }).inputValue(), '2026-09-10');
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    await page.getByLabel('Target price', { exact: true }).fill('106');
    await page.getByRole('button', { name: 'Open draft', exact: true }).click();
    assert.equal(await page.getByLabel('Target price', { exact: true }).inputValue(), target);
    await page.getByRole('button', { name: 'Change strategy', exact: true }).click();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('dialog').count(), 0);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'No mobile page overflow');
    await page.getByRole('button', { name: 'Heatmap', exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: '.wrangler/consolidated-mobile.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS chart views, keyboard/pointer inspection, thesis isolation, grouped picker, explicit Apply, draft restore and mobile');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
